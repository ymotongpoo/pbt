// Package main implements pbtgen, which writes generators for the types of a
// package as Go source, the way PropEr derives generators from type
// declarations. The generated code lives in the package itself, so it can
// fill unexported fields, and it is checked by the compiler rather than
// built by reflection at run time.
//
// Usage, typically from a go:generate directive in the package:
//
//	//go:generate go run go.ymotongpoo.com/pbt/cmd/pbtgen -type Order,Customer
//
// For each type T, pbtgen writes a function GenT that returns pbt.Gen[T];
// the -prefix flag replaces Gen, and a name the package already declares is
// an error. Files that the build constraints exclude on the current platform
// are left out, as go build leaves them out.
// Fields may carry a pbt struct tag: "-" leaves the field zero, "min=A,max=B"
// bounds a number or the length of a string, slice or map, and "gen=EXPR"
// uses the Go expression EXPR as the field's generator. Types from other
// packages fall back to pbt.Make. Recursive types, including mutually
// recursive ones, are generated through pbt.Bounded, with the recursive
// fields zero in the leaves, so that one value holds about size nodes.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/build"
	"go/format"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// generator holds what one run of pbtgen knows about the package.
type generator struct {
	pkg       *types.Package
	prefix    string // of the generated function names
	requested map[string]bool
	imports   map[string]string // import path -> name
	funcs     []string
}

// Generate type-checks the package in dir, leaving out test files, files
// that the build constraints exclude for the current platform, files written
// by pbtgen and the output file itself, and returns the source of a file
// with a generator function named prefix+T for each named type T.
func Generate(dir string, typeNames []string, output, prefix string) ([]byte, error) {
	fset := token.NewFileSet()
	files, name, err := parsePackage(fset, dir, output)
	if err != nil {
		return nil, err
	}
	conf := types.Config{Importer: importer.ForCompiler(fset, "source", nil), Error: func(error) {}}
	pkg, err := conf.Check(name, fset, files, nil)
	if err != nil {
		return nil, fmt.Errorf("type-checking %s: %v", dir, err)
	}
	if prefix == "" {
		return nil, fmt.Errorf("the prefix of the generated functions must not be empty")
	}
	g := &generator{pkg: pkg, prefix: prefix, requested: map[string]bool{}, imports: map[string]string{}}
	for _, n := range typeNames {
		g.requested[n] = true
	}
	for _, n := range typeNames {
		obj := pkg.Scope().Lookup(n)
		tn, ok := obj.(*types.TypeName)
		if !ok {
			return nil, fmt.Errorf("%s is not a type in package %s", n, name)
		}
		if taken := pkg.Scope().Lookup(prefix + n); taken != nil {
			return nil, fmt.Errorf("cannot write %s for %s: package %s already declares it at %s; choose another -prefix",
				prefix+n, n, name, fset.Position(taken.Pos()))
		}
		if err := g.emitType(tn); err != nil {
			return nil, err
		}
	}
	return g.source(name)
}

// parsePackage parses the files of the package in dir that go build would
// compile on this platform, minus the test files, the files pbtgen wrote
// and the output file.
func parsePackage(fset *token.FileSet, dir, output string) ([]*ast.File, string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, "", err
	}
	var files []*ast.File
	var name string
	for _, e := range entries {
		fn := e.Name()
		if e.IsDir() || !strings.HasSuffix(fn, ".go") || strings.HasSuffix(fn, "_test.go") || fn == output {
			continue
		}
		if ok, err := build.Default.MatchFile(dir, fn); err != nil || !ok {
			continue
		}
		path := filepath.Join(dir, fn)
		if generatedByPbtgen(path) {
			continue
		}
		f, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			return nil, "", err
		}
		if name == "" {
			name = f.Name.Name
		}
		files = append(files, f)
	}
	if name == "" {
		return nil, "", fmt.Errorf("no Go package in %s", dir)
	}
	return files, name, nil
}

func (g *generator) source(pkgName string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by pbtgen; DO NOT EDIT.\n// SPDX-License-Identifier: Apache-2.0\n\npackage %s\n\n", pkgName)
	paths := make([]string, 0, len(g.imports)+1)
	paths = append(paths, "go.ymotongpoo.com/pbt")
	for p := range g.imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	b.WriteString("import (\n")
	for _, p := range paths {
		fmt.Fprintf(&b, "\t%q\n", p)
	}
	b.WriteString(")\n\n")
	for _, f := range g.funcs {
		b.WriteString(f)
		b.WriteString("\n")
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), fmt.Errorf("formatting the generated code: %v", err)
	}
	return src, nil
}

// emitType writes the generator function of a named type.
func (g *generator) emitType(tn *types.TypeName) error {
	named, ok := tn.Type().(*types.Named)
	if !ok {
		return fmt.Errorf("%s is an alias; generate the aliased type instead", tn.Name())
	}
	name := tn.Name()
	recursive := g.reaches(named.Underlying(), named, map[types.Type]bool{})
	var body string
	var err error
	if recursive {
		leaf, err1 := g.expr(named, tag{}, named, true, "", named)
		node, err2 := g.expr(named, tag{}, named, false, "pbt.Lazy("+g.prefix+name+")", named)
		if err1 != nil || err2 != nil {
			return fmt.Errorf("%s: %v%v", name, err1, err2)
		}
		body = fmt.Sprintf("return pbt.Bounded(%s, %s)", leaf, node)
	} else {
		body, err = g.expr(named, tag{}, nil, false, "", named)
		if err != nil {
			return fmt.Errorf("%s: %v", name, err)
		}
		body = "return " + body
	}
	fn := g.prefix + name
	g.funcs = append(g.funcs, fmt.Sprintf("// %s generates %s values.\nfunc %s() pbt.Gen[%s] {\n\t%s\n}\n", fn, name, fn, name, body))
	return nil
}

// reaches reports whether from contains target through fields, elements,
// keys and pointers, which is what makes target recursive.
func (g *generator) reaches(from, target types.Type, seen map[types.Type]bool) bool {
	if from == target {
		return true
	}
	if seen[from] {
		return false
	}
	seen[from] = true
	switch t := from.(type) {
	case *types.Named:
		return t.Obj().Pkg() == g.pkg && g.reaches(t.Underlying(), target, seen)
	case *types.Pointer:
		return g.reaches(t.Elem(), target, seen)
	case *types.Slice:
		return g.reaches(t.Elem(), target, seen)
	case *types.Array:
		return g.reaches(t.Elem(), target, seen)
	case *types.Map:
		return g.reaches(t.Key(), target, seen) || g.reaches(t.Elem(), target, seen)
	case *types.Struct:
		for i := range t.NumFields() {
			if g.reaches(t.Field(i).Type(), target, seen) {
				return true
			}
		}
	}
	return false
}

type tag struct {
	skip     bool
	min, max string
	gen      string
}

func parseTag(s string) (tag, error) {
	var tg tag
	if s == "-" {
		tg.skip = true
		return tg, nil
	}
	for _, part := range strings.Split(s, ",") {
		part = strings.TrimSpace(part)
		if part == "" {
			continue
		}
		k, v, ok := strings.Cut(part, "=")
		if !ok {
			return tg, fmt.Errorf("invalid pbt tag %q", part)
		}
		switch k {
		case "min":
			tg.min = v
		case "max":
			tg.max = v
		case "gen":
			tg.gen = v
		default:
			return tg, fmt.Errorf("invalid pbt tag %q", part)
		}
	}
	return tg, nil
}

// expr returns the Go expression of a generator for t. expand is the named
// type whose function is being written: its body is expanded instead of
// calling the function, and only at the top. When self is set, references
// to self inside t use selfExpr, or the zero value when leaf is set, which
// is how recursive types are built.
func (g *generator) expr(t types.Type, tg tag, self types.Type, leaf bool, selfExpr string, expand types.Type) (string, error) {
	if tg.gen != "" {
		return tg.gen, nil
	}
	if self != nil && t == self && !leaf && selfExpr != "" && t != expand {
		return selfExpr, nil
	}
	switch u := t.(type) {
	case *types.Named:
		if u.Obj().Pkg() != g.pkg {
			return fmt.Sprintf("pbt.Make[%s]()", g.typeString(t)), nil
		}
		if g.requested[u.Obj().Name()] && t != expand {
			if self != nil && leaf && g.reaches(t, self, map[types.Type]bool{}) {
				return fmt.Sprintf("pbt.Just(%s{})", g.typeString(t)), nil
			}
			return fmt.Sprintf("pbt.Lazy(%s%s)", g.prefix, u.Obj().Name()), nil
		}
		switch under := u.Underlying().(type) {
		case *types.Struct:
			return g.structExpr(under, g.typeString(t), self, leaf, selfExpr)
		default:
			inner, err := g.expr(under, tg, self, leaf, selfExpr, nil)
			if err != nil {
				return "", err
			}
			return fmt.Sprintf("pbt.Map(%s, func(x %s) %s { return %s(x) })", inner, g.typeString(under), g.typeString(t), g.typeString(t)), nil
		}
	case *types.Basic:
		return g.basicExpr(u, tg)
	case *types.Pointer:
		if self != nil && leaf && (u.Elem() == self || g.reaches(u.Elem(), self, map[types.Type]bool{})) {
			return fmt.Sprintf("pbt.Just[%s](nil)", g.typeString(t)), nil
		}
		elem, err := g.expr(u.Elem(), tag{}, self, leaf, selfExpr, nil)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("pbt.Ptr(%s, true)", elem), nil
	case *types.Slice:
		if self != nil && leaf && g.reaches(u, self, map[types.Type]bool{}) {
			return fmt.Sprintf("pbt.Just[%s](nil)", g.typeString(t)), nil
		}
		elem, err := g.expr(u.Elem(), tag{}, self, leaf, selfExpr, nil)
		if err != nil {
			return "", err
		}
		if tg.min != "" || tg.max != "" {
			return fmt.Sprintf("pbt.SliceOfN(%s, %s, %s)", elem, orDefault(tg.min, "0"), orDefault(tg.max, "-1")), nil
		}
		return fmt.Sprintf("pbt.SliceOf(%s)", elem), nil
	case *types.Array:
		elem, err := g.expr(u.Elem(), tag{}, self, leaf, selfExpr, nil)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("pbt.Custom(%q, func(t *pbt.T) %s {\n\tvar v %s\n\tfor i := range v {\n\t\tv[i] = %s.Draw(t, \"\")\n\t}\n\treturn v\n})",
			g.typeString(t), g.typeString(t), g.typeString(t), elem), nil
	case *types.Map:
		if self != nil && leaf && g.reaches(u, self, map[types.Type]bool{}) {
			return fmt.Sprintf("pbt.Just[%s](nil)", g.typeString(t)), nil
		}
		key, err := g.expr(u.Key(), tag{}, self, leaf, selfExpr, nil)
		if err != nil {
			return "", err
		}
		val, err := g.expr(u.Elem(), tag{}, self, leaf, selfExpr, nil)
		if err != nil {
			return "", err
		}
		if tg.min != "" || tg.max != "" {
			return fmt.Sprintf("pbt.MapOfN(%s, %s, %s, %s)", key, val, orDefault(tg.min, "0"), orDefault(tg.max, "-1")), nil
		}
		return fmt.Sprintf("pbt.MapOf(%s, %s)", key, val), nil
	case *types.Struct:
		return g.structExpr(u, g.typeString(t), self, leaf, selfExpr)
	}
	return "", fmt.Errorf("cannot generate %s; add a pbt:\"gen=...\" tag", g.typeString(t))
}

func orDefault(s, d string) string {
	if s == "" {
		return d
	}
	return s
}

func (g *generator) basicExpr(b *types.Basic, tg tag) (string, error) {
	kind := b.Kind()
	switch {
	case kind == types.Bool:
		return "pbt.Bool()", nil
	case kind == types.String:
		if tg.min != "" || tg.max != "" {
			return fmt.Sprintf("pbt.StringN(%s, %s)", orDefault(tg.min, "0"), orDefault(tg.max, "-1")), nil
		}
		return "pbt.String()", nil
	case b.Info()&types.IsInteger != 0:
		name := b.Name()
		if tg.min != "" || tg.max != "" {
			lo, hi := tg.min, tg.max
			if lo == "" {
				lo = minConst(b)
			}
			if hi == "" {
				hi = maxConst(b)
			}
			if strings.HasPrefix(lo, "math.") || strings.HasPrefix(hi, "math.") {
				g.imports["math"] = "math"
			}
			return fmt.Sprintf("pbt.IntegerRange[%s](%s, %s)", name, lo, hi), nil
		}
		return fmt.Sprintf("pbt.Integer[%s]()", name), nil
	case kind == types.Float64 || kind == types.Float32:
		fn := "Float64"
		if kind == types.Float32 {
			fn = "Float32"
		}
		if tg.min != "" || tg.max != "" {
			lo, hi := tg.min, tg.max
			if lo == "" {
				lo = "-math.Max" + fn
				g.imports["math"] = "math"
			}
			if hi == "" {
				hi = "math.Max" + fn
				g.imports["math"] = "math"
			}
			return fmt.Sprintf("pbt.%sRange(%s, %s)", fn, lo, hi), nil
		}
		return fmt.Sprintf("pbt.%s()", fn), nil
	}
	return "", fmt.Errorf("cannot generate %s; add a pbt:\"gen=...\" tag", b.Name())
}

// minConst and maxConst name the bounds of an integer type.
func minConst(b *types.Basic) string {
	if b.Info()&types.IsUnsigned != 0 {
		return "0"
	}
	return "math.Min" + strings.ToUpper(b.Name()[:1]) + b.Name()[1:]
}

func maxConst(b *types.Basic) string {
	if b.Kind() == types.Uintptr {
		return "^uintptr(0)"
	}
	return "math.Max" + strings.ToUpper(b.Name()[:1]) + b.Name()[1:]
}

// structExpr returns a Custom generator that draws every field that is not
// skipped, including unexported ones.
func (g *generator) structExpr(st *types.Struct, typeName string, self types.Type, leaf bool, selfExpr string) (string, error) {
	label := typeName
	if strings.HasPrefix(label, "struct") {
		label = "struct"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "pbt.Custom(%q, func(t *pbt.T) %s {\n\tvar v %s\n", label, typeName, typeName)
	for i := range st.NumFields() {
		f := st.Field(i)
		tg, err := parseTag(reflect_tag(st.Tag(i)))
		if err != nil {
			return "", fmt.Errorf("field %s: %v", f.Name(), err)
		}
		if tg.skip {
			continue
		}
		e, err := g.expr(f.Type(), tg, self, leaf, selfExpr, nil)
		if err != nil {
			return "", fmt.Errorf("field %s: %v", f.Name(), err)
		}
		fmt.Fprintf(&b, "\tv.%s = %s.Draw(t, \"\")\n", f.Name(), e)
	}
	b.WriteString("\treturn v\n})")
	return b.String(), nil
}

// reflect_tag extracts the pbt key from a struct tag string without
// importing reflect's StructTag, which needs the raw tag.
func reflect_tag(raw string) string {
	for raw != "" {
		i := 0
		for i < len(raw) && raw[i] == ' ' {
			i++
		}
		raw = raw[i:]
		if raw == "" {
			break
		}
		i = 0
		for i < len(raw) && raw[i] > ' ' && raw[i] != ':' && raw[i] != '"' {
			i++
		}
		if i == 0 || i+1 >= len(raw) || raw[i] != ':' || raw[i+1] != '"' {
			break
		}
		name := raw[:i]
		raw = raw[i+1:]
		i = 1
		for i < len(raw) && raw[i] != '"' {
			if raw[i] == '\\' {
				i++
			}
			i++
		}
		if i >= len(raw) {
			break
		}
		quoted := raw[:i+1]
		raw = raw[i+1:]
		if name == "pbt" {
			v, err := strconv.Unquote(quoted)
			if err != nil {
				return ""
			}
			return v
		}
	}
	return ""
}

// typeString writes a type as Go source from inside the package, recording
// the imports it needs. Anonymous structs are written one field per line,
// which keeps the generated code in gofmt's layout.
func (g *generator) typeString(t types.Type) string {
	if st, ok := t.(*types.Struct); ok {
		var b strings.Builder
		b.WriteString("struct {\n")
		for i := range st.NumFields() {
			f := st.Field(i)
			fmt.Fprintf(&b, "\t%s %s", f.Name(), g.typeString(f.Type()))
			if tag := st.Tag(i); tag != "" {
				fmt.Fprintf(&b, " %s", strconv.Quote(tag))
			}
			b.WriteString("\n")
		}
		b.WriteString("}")
		return b.String()
	}
	return types.TypeString(t, func(p *types.Package) string {
		if p == g.pkg {
			return ""
		}
		g.imports[p.Path()] = p.Name()
		return p.Name()
	})
}

// generatedByPbtgen reports whether a file was written by this tool, so that
// an earlier output does not take part in type-checking a later one.
func generatedByPbtgen(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	var head [64]byte
	n, _ := f.Read(head[:])
	return strings.HasPrefix(string(head[:n]), "// Code generated by pbtgen")
}

func outputPath(dir string, explicit string) string {
	if explicit != "" {
		return explicit
	}
	return filepath.Join(dir, "pbt_gen.go")
}
